"""Writes THIRD-PARTY-LICENCES.txt: the licence files of every Rust library
compiled into the photo remaker's WebAssembly, as each library ships them.

    python3 licences.py      (from tools/photo-remake, after a cargo build)
"""
import json
import os
import subprocess

meta = json.loads(subprocess.run(
    ["cargo", "metadata", "--format-version", "1", "--filter-platform", "wasm32-unknown-unknown"],
    check=True, capture_output=True, text=True).stdout)
packages = {p["id"]: p for p in meta["packages"]}
nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
seen, stack = set(), [meta["resolve"]["root"]]
while stack:
    pid = stack.pop()
    if pid in seen:
        continue
    seen.add(pid)
    for dep in nodes[pid]["deps"]:
        if any(kind["kind"] is None for kind in dep["dep_kinds"]):
            stack.append(dep["pkg"])

out = ["Licences of the Rust libraries compiled into the photo remaker's WebAssembly",
       "(supabase/functions/_shared/photo-remake-wasm.ts). Each is used under the",
       "first licence named in NOTICES.md; its own licence files follow, as shipped",
       "in its source. GENERATED by tools/photo-remake/licences.py.", ""]
for pid in sorted(seen, key=lambda x: (packages[x]["name"], packages[x]["version"])):
    p = packages[pid]
    if p["name"] == "photo-remake":
        continue
    folder = os.path.dirname(p["manifest_path"])
    files = sorted(f for f in os.listdir(folder)
                   if f.upper().startswith(("LICENSE", "LICENCE", "COPYING", "UNLICENSE")))
    out += ["=" * 78, f"{p['name']} {p['version']}  ({p.get('license')})  {p.get('repository') or ''}", "=" * 78]
    if not files:
        out.append(f"(no licence file in the published source; licence by its manifest: {p.get('license')})")
    for name in files:
        with open(os.path.join(folder, name), encoding="utf-8", errors="replace") as fh:
            out += [f"--- {name}", fh.read().rstrip()]
    out.append("")
with open("THIRD-PARTY-LICENCES.txt", "w", encoding="utf-8") as fh:
    fh.write("\n".join(out) + "\n")
print(f"{len(seen) - 1} libraries written to THIRD-PARTY-LICENCES.txt")
