// Builds the Rust photo remaker to WebAssembly and writes it where the
// photo-check function can import it, as text:
//
//   node tools/photo-remake/build.mjs            build, write, print the SHA-256
//   node tools/photo-remake/build.mjs --check    build, and fail if the committed
//                                                copy is not what this source builds
//
// WHY TEXT. A Supabase function is deployed from its folder's code; a .wasm
// file beside it is left behind unless the project lists it as a static file.
// As a TypeScript module holding base64, the same bytes reach Supabase's
// functions and the Postgres edition's Node with nothing to configure.
//
// WHY A CHECKSUM. Nobody reviews 900 KB of base64. The SHA-256 of the
// WebAssembly is written beside it; tests/a-photo-is-remade-in-rust.mjs checks
// the base64 still decodes to those bytes, and anybody with Rust 1.97.0
// (rust-toolchain.toml) can run --check to confirm the source builds them.
import { execFileSync } from 'node:child_process';
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../..');
const target = path.join(root, 'supabase/functions/_shared/photo-remake-wasm.ts');
const check = process.argv.includes('--check');

execFileSync('cargo', ['build', '--release', '--locked', '--target', 'wasm32-unknown-unknown'], {
  cwd: here, stdio: 'inherit',
});
const wasm = fs.readFileSync(path.join(here, 'target/wasm32-unknown-unknown/release/photo_remake.wasm'));
const sha256 = crypto.createHash('sha256').update(wasm).digest('hex');
const text = [
  '// GENERATED by tools/photo-remake/build.mjs from tools/photo-remake (Rust, image 0.25.10).',
  '// Do not edit. The source is the Rust; README.md there says how to rebuild and compare.',
  `export const WASM_SHA256 = '${sha256}';`,
  `export const WASM_BASE64 = '${wasm.toString('base64')}';`,
  '',
].join('\n');

if (check) {
  const committed = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : '';
  if (committed !== text) {
    console.error(`The committed photo-remake-wasm.ts is not what this source builds (built ${sha256}).`);
    process.exit(1);
  }
  console.log(`The committed WebAssembly is what this source builds: ${sha256}`);
} else {
  fs.writeFileSync(target, text);
  console.log(`Wrote ${path.relative(root, target)} (${wasm.length} bytes of WebAssembly, sha256 ${sha256})`);
}
